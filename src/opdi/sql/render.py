"""SQL definitions of the published tables and of views in the layout of release v0.0.2.

The published OPDI files can be queried with SQL without downloading them:

* **Trino** (a distributed SQL engine) reads them where they are stored.
  :func:`trino_tables` defines one external table per published folder (a
  table whose rows are the Parquet files of that folder) and
  :func:`trino_views` defines views that give the separate flight list,
  events and measurements tables in the layout of release v0.0.2. In them
  the identifiers are text and do not match the identifiers of release
  v0.0.2, and ``version`` holds the version of the method of each row.
* **DuckDB** (an SQL engine that runs inside a Python or R session) reads
  the files directly from a folder or over the web.
  :func:`duckdb_views_template` gives the views; :func:`opdi.published.duckdb_views`
  fills in the files to read.

Every column name, type and description is taken from
:mod:`opdi.output.schema`, so the SQL always matches the files. The files
``sql/trino/tables.sql``, ``sql/trino/views.sql`` and ``sql/views.sql`` in
this package are the output of this module with the default arguments.
Regenerate them with::

    python -m opdi.sql.render
"""

from pathlib import Path
from typing import Iterable, List

from opdi.output.schema import (
    CLASSIC_EVENT_COLUMNS,
    CLASSIC_FLIGHT_LIST,
    CLASSIC_MEASUREMENTS_ALWAYS,
    FLIGHT_EVENTS,
    FLIGHT_INDEX,
    FLIGHT_LIST,
    MEASUREMENT_COLUMNS,
    MEASUREMENT_SUFFIX,
    MEASUREMENT_VERSION,
    RELEASE,
    Column,
)

#: Trino catalog that holds the tables. A placeholder until the name on the
#: OpenSky Trino instance is set.
DEFAULT_CATALOG = "minio"

#: Trino schema (a group of tables inside a catalog). A placeholder until the
#: name on the OpenSky Trino instance is set.
DEFAULT_SCHEMA = "opdi"

#: Folder of the published files of the release.
DEFAULT_LOCATION = f"s3a://eurocontrol/opdi/{RELEASE}/published"

#: Placeholders in :func:`duckdb_views_template` for the lists of files.
FLIGHT_LIST_FILES = "__FLIGHT_LIST_FILES__"
FLIGHT_EVENTS_FILES = "__FLIGHT_EVENTS_FILES__"
FLIGHT_INDEX_FILES = "__FLIGHT_INDEX_FILES__"

#: First line of the ``flight_index`` view in :func:`duckdb_views_template`.
#: That view is the last statement of the text, so a reader whose folder
#: has no index cuts the text at this line.
FLIGHT_INDEX_VIEW_START = "-- The monthly flight index."

_TRINO_TYPES = {
    "string": "varchar",
    "double": "double",
    "date": "date",
    "timestamp": "timestamp",
    "boolean": "boolean",
    "bigint": "bigint",
    "array<string>": "array(varchar)",
}

_TABLES = (
    (
        "flight_list",
        FLIGHT_LIST,
        f"OPDI flight list, release {RELEASE}: one row per flight, one file per day.",
    ),
    (
        "flight_events",
        FLIGHT_EVENTS,
        f"OPDI flight events, release {RELEASE}: one row per event, with the event's "
        "measurements and its flight's columns, one file per day.",
    ),
    (
        "flight_index",
        FLIGHT_INDEX,
        f"OPDI flight index, release {RELEASE}: which daily file holds each flight, one "
        "file per month.",
    ),
)


def _quote(text: str) -> str:
    """``text`` as an SQL string literal."""
    return "'" + text.replace("'", "''") + "'"


def _trino_header(catalog: str, schema: str) -> str:
    return (
        "-- Generated by opdi.sql.render from the declared schema "
        "(opdi.output.schema). Do not edit.\n"
        f"-- Catalog {catalog!r} and schema {schema!r} are placeholders: set them to the\n"
        "-- names used on the Trino instance, with\n"
        "--     python -m opdi.sql.render --catalog <catalog> --schema <schema>\n"
    )


def trino_tables(
    catalog: str = DEFAULT_CATALOG,
    schema: str = DEFAULT_SCHEMA,
    location: str = DEFAULT_LOCATION,
) -> str:
    """Trino statements that define the published tables.

    One external table for each of the folders ``flight_list``,
    ``flight_events`` and ``index``. Trino reads every Parquet file in the
    folder, so a newly published day is visible at once.

    Args:
        catalog: Trino catalog of the tables.
        schema: Trino schema of the tables.
        location: The published folder of the release.

    Returns:
        The ``CREATE TABLE`` statements, with a comment on every column.
    """
    location = location.rstrip("/")
    parts = [_trino_header(catalog, schema) + f"-- Location of the published files: {location}\n"]
    for table, columns, comment in _TABLES:
        folder = "index" if table == "flight_index" else table
        width = max(len(c.name) for c in columns)
        lines = [
            f"    {c.name.ljust(width)} {_TRINO_TYPES[c.dtype]} COMMENT {_quote(c.description)}"
            for c in columns
        ]
        parts.append(
            f"CREATE TABLE IF NOT EXISTS {catalog}.{schema}.{table} (\n"
            + ",\n".join(lines)
            + "\n)\n"
            + f"COMMENT {_quote(comment)}\n"
            + "WITH (\n"
            + f"    external_location = {_quote(f'{location}/{folder}')},\n"
            + "    format = 'PARQUET'\n"
            + ");\n"
        )
    return "\n".join(parts)


def _measurements_query(source: str, columns: Iterable[Column]) -> str:
    """The rows of the measurements view, one SELECT per measurement type.

    Plain SQL that Trino and DuckDB run the same way. The types of release
    v0.0.2 give a row for every event; the others only where they have a
    value.
    """
    parts = []
    for c in columns:
        where = "" if c.source in CLASSIC_MEASUREMENTS_ALWAYS else f"\nWHERE {c.name} IS NOT NULL"
        parts.append(
            "SELECT\n"
            f"    event_id || {_quote(MEASUREMENT_SUFFIX[c.source])} AS id,\n"
            "    event_id,\n"
            f"    {_quote(c.source)} AS type,\n"
            f"    CAST({c.name} AS DOUBLE) AS value,\n"
            f"    {_quote(MEASUREMENT_VERSION[c.source])} AS version\n"
            f"FROM {source}{where}"
        )
    return "\nUNION ALL\n".join(parts)


#: The SQL comment above the three views in the layout of release v0.0.2.
_V0_COMMENT = (
    "-- The separate flight list, events and measurements tables in the layout of\n"
    "-- release v0.0.2. The identifiers are text and do not match the identifiers of\n"
    "-- release v0.0.2, which were 64-bit integers. The version column holds the\n"
    "-- version of the method that produced each row.\n"
)


def trino_views(catalog: str = DEFAULT_CATALOG, schema: str = DEFAULT_SCHEMA) -> str:
    """Trino statements that define three views in the layout of release v0.0.2.

    The separate flight list, events and measurements tables of release
    v0.0.2, over the published tables. The identifiers are text and do not
    match the identifiers of release v0.0.2, and ``version`` holds the
    version of the method that produced each row.

    * ``flight_list_v0``: the columns of the v0.0.2 flight list, with their
      v0.0.2 names (lower case) in their v0.0.2 order.
    * ``events``: the events alone, with the ten columns of release v0.0.2.
    * ``measurements``: one row per measurement, with the columns ``id``,
      ``event_id``, ``type``, ``value`` and ``version`` of release v0.0.2.
      As in release v0.0.2, every event has a distance flown row and a time
      passed row, also when the value is empty; the other types give a row
      only when they have a value. The ``id`` is the event id followed by
      the suffix of the measurement type.

    Args:
        catalog: Trino catalog of the tables.
        schema: Trino schema of the tables.

    Returns:
        The ``CREATE OR REPLACE VIEW`` statements.
    """
    prefix = f"{catalog}.{schema}"
    events = ",\n".join(
        f"    {name} AS {classic}" if name != classic else f"    {name}"
        for name, classic in CLASSIC_EVENT_COLUMNS.items()
    )
    flights = ",\n".join(
        f"    {name} AS {classic}" if name != classic else f"    {name}"
        for name, classic in CLASSIC_FLIGHT_LIST.items()
    )
    return "\n".join(
        [
            _trino_header(catalog, schema) + _V0_COMMENT,
            f"-- Events in the layout of release v0.0.2.\n"
            f"CREATE OR REPLACE VIEW {prefix}.events AS\nSELECT\n{events}\n"
            f"FROM {prefix}.flight_events;\n",
            "-- Measurements in the layout of release v0.0.2: one row per measurement.\n"
            "-- Every event has a distance and a time row, also when empty, as in v0.0.2.\n"
            f"CREATE OR REPLACE VIEW {prefix}.measurements AS\n"
            f"{_measurements_query(f'{prefix}.flight_events', MEASUREMENT_COLUMNS)};\n",
            "-- The flight list in the layout of release v0.0.2: its column names and order.\n"
            f"CREATE OR REPLACE VIEW {prefix}.flight_list_v0 AS\nSELECT\n{flights}\n"
            f"FROM {prefix}.flight_list;\n",
        ]
    )


def duckdb_views_template() -> str:
    """DuckDB statements that define six views over published files.

    The views have the names of the Trino tables and views:

    * ``flight_list``: the flight list files.
    * ``flight_events``: the flight events files as published.
    * ``flight_list_v0``, ``events`` and ``measurements``: the separate
      flight list, events and measurements tables in the layout of release
      v0.0.2, with the same rows as the Trino views (see
      :func:`trino_views`).
    * ``flight_index``: the monthly flight index files. This is the last
      statement and starts at the line :data:`FLIGHT_INDEX_VIEW_START`.

    The text holds three placeholders, :data:`FLIGHT_LIST_FILES`,
    :data:`FLIGHT_EVENTS_FILES` and :data:`FLIGHT_INDEX_FILES`, for the files
    to read (a DuckDB list of paths, or a path with a ``*`` wildcard). Use
    :func:`opdi.published.duckdb_views` to fill them in.
    """
    events = ",\n".join(
        f"    {name} AS {classic}" if name != classic else f"    {name}"
        for name, classic in CLASSIC_EVENT_COLUMNS.items()
    )
    flights = ",\n".join(
        f"    {name} AS {classic}" if name != classic else f"    {name}"
        for name, classic in CLASSIC_FLIGHT_LIST.items()
    )
    return "\n".join(
        [
            "-- Generated by opdi.sql.render from the declared schema "
            "(opdi.output.schema). Do not edit.\n"
            "-- DuckDB views over the published OPDI files. opdi.published.duckdb_views()\n"
            f"-- replaces {FLIGHT_LIST_FILES} and {FLIGHT_EVENTS_FILES} with the files to read.\n",
            "-- The flight list files.\n"
            "CREATE OR REPLACE VIEW flight_list AS\n"
            f"SELECT * FROM read_parquet({FLIGHT_LIST_FILES}, union_by_name = true);\n",
            "-- The flight events files, as published.\n"
            "CREATE OR REPLACE VIEW flight_events AS\n"
            f"SELECT * FROM read_parquet({FLIGHT_EVENTS_FILES}, union_by_name = true);\n",
            _V0_COMMENT + "-- Events in the layout of release v0.0.2.\n"
            f"CREATE OR REPLACE VIEW events AS\nSELECT\n{events}\n"
            "FROM flight_events;\n",
            "-- Measurements in the layout of release v0.0.2: one row per measurement.\n"
            "-- Every event has a distance and a time row, also when empty, as in v0.0.2.\n"
            "CREATE OR REPLACE VIEW measurements AS\n"
            f"{_measurements_query('flight_events', MEASUREMENT_COLUMNS)};\n",
            "-- The flight list in the layout of release v0.0.2: its column names and order.\n"
            f"CREATE OR REPLACE VIEW flight_list_v0 AS\nSELECT\n{flights}\n"
            "FROM flight_list;\n",
            f"{FLIGHT_INDEX_VIEW_START} Left out when the folder has no index.\n"
            "CREATE OR REPLACE VIEW flight_index AS\n"
            f"SELECT * FROM read_parquet({FLIGHT_INDEX_FILES}, union_by_name = true);\n",
        ]
    )


#: This package's folder, where the SQL files are written by default.
_PACKAGE_FOLDER = Path(__file__).resolve().parent


def write_files(
    catalog: str = DEFAULT_CATALOG,
    schema: str = DEFAULT_SCHEMA,
    location: str = DEFAULT_LOCATION,
    folder: Path = _PACKAGE_FOLDER,
) -> List[Path]:
    """Write the three SQL files into ``folder``.

    Returns:
        The paths written.
    """
    outputs = {
        folder / "trino" / "tables.sql": trino_tables(catalog, schema, location),
        folder / "trino" / "views.sql": trino_views(catalog, schema),
        folder / "views.sql": duckdb_views_template(),
    }
    for path, text in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
    return list(outputs)


def main(argv=None) -> int:
    """Command line: write the SQL files, optionally for other names."""
    import argparse

    parser = argparse.ArgumentParser(description="Write the OPDI SQL definitions.")
    parser.add_argument("--catalog", default=DEFAULT_CATALOG, help="Trino catalog.")
    parser.add_argument("--schema", default=DEFAULT_SCHEMA, help="Trino schema.")
    parser.add_argument(
        "--location", default=DEFAULT_LOCATION, help="Published folder of the release."
    )
    parser.add_argument(
        "--out",
        type=Path,
        default=Path(__file__).resolve().parent,
        help="Folder to write into (default: this package).",
    )
    args = parser.parse_args(argv)
    for path in write_files(args.catalog, args.schema, args.location, args.out):
        print(path)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
